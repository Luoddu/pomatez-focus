// Hidden real Electron chain, synthetic tasks and no live external writes.
const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { FocusService } = require('../app/electron/build/focus/service.js');
process.env.POMATEZ_HEADLESS = '1';
process.env.POMATEZ_PROFILE = path.join(__dirname, '../artifacts/test-profiles', randomUUID());
const tasks = [1, 2].map(n => ({id: `p${n}`, taskId: `t${n}`, planId: `p${n}`, title: `Synthetic ${n} · 第 1 个番茄`, description: `Details ${n}`, source: 'feishu', sourceKey: 'synthetic', quadrant: 'iu'}));
let writes = [], shared = [];
FocusService.prototype.status = () => ({configured: true, sourceKey: 'synthetic'});
FocusService.prototype.today = async () => structuredClone(tasks);
FocusService.prototype.history = async () => ({sourceKey: 'synthetic', records: shared, missing: 0});
FocusService.prototype.sync = async record => { writes.push(record); return {synced: true, planId: record.task.planId}; };
FocusService.prototype.archiveHistory = async record => { const r = {...record, cloudSynced: true, sync: 'synced'}; shared = [r]; return r; };
require('../app/electron/build/main.js');
const delay = ms => new Promise(r => setTimeout(r, ms));
const timeout = setTimeout(() => app.exit(2), 60000);
app.whenReady().then(async () => {
 try {
  let win;
  const until = async f => {for(let i=0;i<240;i++){if(await f()) return; await delay(30);} throw Error('Timed out: '+f);};
  await until(() => {win=BrowserWindow.getAllWindows()[0]; return win && !win.webContents.isLoadingMainFrame() && win.webContents.getURL().startsWith('file:');});
  const js = s => win.webContents.executeJavaScript(s, true);
  const stored = () => js("JSON.parse(localStorage.getItem('pomatez-focus-v1'))");
  const click = name => js(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.getAttribute('aria-label')===${JSON.stringify(name)}||b.textContent.trim()===${JSON.stringify(name)});if(!b||b.disabled)throw Error('Unavailable: '+${JSON.stringify(name)});b.click()})()`);
  const choose = value => js(`(()=>{const e=document.querySelector('#active-task-choice');Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('change',{bubbles:true}))})()`);
  const change = async value => {await click('更换任务');await choose(value);await click('确认更换');};
  await until(() => js("document.querySelectorAll('.chips .chip').length===2"));
  await click('开始专注');
  await until(async () => (await stored())?.active?.status==='active');
  await delay(1600);
  const first=(await stored()).active;
  assert.equal(first.task.kind, 'free');
  await change('p1');
  let next=(await stored()).active;
  assert.equal(next.task.id,'p1'); assert.equal(next.id,first.id); assert.equal(next.startedAt,first.startedAt); assert.ok(next.elapsedSeconds>=first.elapsedSeconds);
  assert.equal(await js("document.querySelector('.ct-description').textContent"),'Details 1');
  assert.equal(writes.length,0);
  console.log('PASS free-to-task retains identity/time, shows details, no premature sync');
  await click('更换任务'); await choose('p2'); await delay(1200);
  const fs = require('node:fs'), shots=path.join(__dirname,'../artifacts/active-task');
  fs.mkdirSync(shots,{recursive:true});
  await win.webContents.capturePage(); await delay(100);
  fs.writeFileSync(path.join(shots,'picker.png'),(await win.webContents.capturePage()).toPNG());
  await click('取消更换');
  assert.equal((await stored()).active.task.id,'p1');
  assert.ok((await stored()).active.elapsedSeconds>next.elapsedSeconds);
  await click('暂停');
  const paused=(await stored()).active;
  await change('p2');
  next=(await stored()).active;
  assert.deepEqual({...next,task:paused.task}, paused);
  assert.equal(await js("document.querySelector('.ct-description').textContent"),'Details 2');
  await change('__free__');
  assert.equal((await stored()).active.task.kind,'free');
  assert.equal((await stored()).active.elapsedSeconds,paused.elapsedSeconds);
  await change('p1');
  console.log('PASS cancel preserves task while ticking; paused task-to-task/free preserves all timing');
  tasks[0].description='Updated details from refresh';
  await new Promise(resolve => {win.webContents.once('did-finish-load',resolve);win.webContents.reload();});
  await until(() => js("document.querySelector('.ct-description')?.textContent==='Updated details from refresh'"));
  assert.equal((await stored()).active.id,first.id);
  assert.equal((await stored()).active.status,'paused');
  assert.equal((await stored()).active.elapsedSeconds,paused.elapsedSeconds);
  tasks[0].description='';
  await new Promise(resolve => {win.webContents.once('did-finish-load',resolve);win.webContents.reload();});
  await until(() => js("!!document.querySelector('.ct-name')&&!document.querySelector('.ct-description')"));
  await delay(300);
  assert.equal(await js("!!document.querySelector('.ct-description')"),false);
  assert.equal(writes.length,0);
  console.log('PASS reload retains assignment/timing and refreshes or clears description');
  await click('继续'); await delay(1100); await click('结束'); await click('确认结束');
  await until(() => js("!!document.querySelector('.review-card')"));
  assert.match(await js("document.querySelector('.review-task').textContent"), /Synthetic 1/);
  await click('记录番茄');
  await until(() => writes.length===1);
  assert.equal(writes[0].task.id,'p1'); assert.equal(writes[0].id,first.id);
  assert.equal((await stored()).records.length,1);
  assert.equal((await stored()).active,null);
  assert.equal(win.isVisible(),false);
  console.log('PASS final confirmation saves and syncs exactly once to corrected plan');
  clearTimeout(timeout);app.exit(0);
 } catch(e){console.error(e);clearTimeout(timeout);app.exit(1);}
});
