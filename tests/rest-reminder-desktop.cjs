const { app, BrowserWindow } = require("electron");
const assert = require("node:assert/strict"), path = require("node:path"), fs = require("node:fs");
if (process.env.POMATEZ_HEADLESS !== "1" || !process.env.POMATEZ_PROFILE) throw Error("Isolated hidden test required");
const { restPopup, restMonitor } = require("../app/electron/build/main");
const wait = ms => new Promise(r => setTimeout(r, ms));
const until = async fn => { for (let n = 0; n < 120; n++) { if (await fn()) return; await wait(30); } throw Error("Window wait timeout"); };
const popup = () => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().endsWith("/assets/rest-reminder.html"));
const root = path.resolve(__dirname, "..");
const checks = [];
app.whenReady().then(async () => {
  try {
    const farm = BrowserWindow.getAllWindows()[0];
    await until(() => farm && !farm.webContents.isLoadingMainFrame());
    await until(() => farm.webContents.executeJavaScript("!!document.querySelector('.focus-app')"));
    const state = restMonitor.snapshot();
    state.status = "recording";
    state.reminder = { key: "test/one", watchedMinutes: 5, excessMinutes: 0, kind: "focus", completedCount: 0 };
    restPopup.update(state);
    await until(() => popup() && !popup().webContents.isLoadingMainFrame());
    const alert = popup(), js = code => alert.webContents.executeJavaScript(code, true);
    await until(() => js("!document.querySelector('button').disabled"));
    assert.equal(alert.isAlwaysOnTop(), true);
    assert.equal(alert.getParentWindow(), null);
    assert.equal(alert.isVisible(), false);
    assert.equal(farm.isAlwaysOnTop(), false);
    assert.equal(farm.isVisible(), false);
    assert.equal(await js("document.querySelectorAll('h2').length"), 1);
    assert.equal(await js("document.querySelectorAll('p').length"), 1);
    assert.equal(await js("document.querySelectorAll('button').length"), 2);
    assert.equal(await js("typeof window.focusApi"), "undefined");
    const presented = await js("window.restReminderApi.state()");
    assert.deepEqual(Object.keys(presented).sort(), ["key", "line"]);
    assert.ok(presented.line.includes("0/12"));
    checks.push("separate parentless topmost window, minimal two-button UI, hidden headless, farm remains hidden/unpinned, narrow presentation only");
    state.reminder.watchedMinutes = 10;
    restPopup.update(state);
    await until(() => js("document.querySelector('p').textContent.includes('10 分钟')"));
    assert.equal(popup(), alert);
    checks.push("threshold updates reuse one window instead of stacking");
    assert.notEqual(alert.webContents.getOSProcessId(), farm.webContents.getOSProcessId());
    await assert.rejects(js("window.restReminderApi.act({key:'stale',action:'focus'})"));
    await assert.rejects(js("window.restReminderApi.act({key:'test/one',action:'quit'})"));
    assert.equal(popup(), alert);
    const intruder = new BrowserWindow({ show: false, webPreferences: {
      preload: path.join(root, "app/electron/build/rest-reminder-preload.js"), contextIsolation: true, sandbox: true, nodeIntegration: false,
    } });
    await intruder.loadFile(path.join(root, "app/electron/build/assets/rest-reminder.html"));
    await assert.rejects(intruder.webContents.executeJavaScript("window.restReminderApi.state()"));
    await assert.rejects(intruder.webContents.executeJavaScript("window.restReminderApi.act({key:'test/one',action:'focus'})"));
    intruder.destroy();
    const staleCompletion = await farm.webContents.executeJavaScript("window.focusApi.restActionResult({id:999,key:'test/one',ok:true}).then(()=>false,()=>true)");
    assert.equal(staleCompletion, true);
    checks.push("invalid/stale actions, foreign renderer and unrequested completion rejected; legitimate popup remains usable");
    const forwarded = [], send = farm.webContents.send.bind(farm.webContents);
    farm.webContents.send = (channel, ...values) => {
      if (channel === 'focus:rest-action') forwarded.push(values[0]); else send(channel, ...values);
    };
    const firstAction = restPopup.act({ key: 'test/one', action: 'focus' });
    const rejectedFirst = assert.rejects(firstAction);
    await assert.rejects(restPopup.act({ key: 'test/one', action: 'sleep' }));
    assert.equal(forwarded.length, 1);
    await assert.rejects(farm.webContents.executeJavaScript(`window.focusApi.restActionResult(${JSON.stringify({ ...forwarded[0], id: 9999, ok: true })})`));
    await farm.webContents.executeJavaScript(`window.focusApi.restActionResult(${JSON.stringify({ ...forwarded[0], ok: false })})`);
    await rejectedFirst;
    assert.equal(popup(), alert);
    const secondAction = restPopup.act({ key: 'test/one', action: 'focus' });
    assert.equal(forwarded.length, 2);
    assert.notEqual(forwarded[0].id, forwarded[1].id);
    await farm.webContents.executeJavaScript(`window.focusApi.restActionResult(${JSON.stringify({ ...forwarded[1], ok: true })})`);
    await secondAction;
    assert.equal(alert.isDestroyed(), true);
    assert.equal(farm.isAlwaysOnTop(), false);
    farm.webContents.send = send;
    restPopup.update(state);
    await until(() => popup() && !popup().webContents.isLoadingMainFrame());
    checks.push("one in-flight action only, mismatched completion rejected, failed action retry works, successful matching completion disposes alert without pinning farm");
    for (const change of [s => { s.settings.supervise = false; }, s => { s.status = 'interrupted'; }, s => { s.reminder = null; }]) {
      const previous = popup();
      const next = JSON.parse(JSON.stringify(state)); change(next); restPopup.update(next);
      assert.equal(previous.isDestroyed(), true);
      assert.equal(popup(), undefined);
      restPopup.update(state);
      await until(() => popup() && !popup().webContents.isLoadingMainFrame());
    }
    checks.push("supervision off, interruption and cleared reminder destroy alert; subsequent threshold can open again");
    const crashed = popup(), farmProcess = farm.webContents.getOSProcessId();
    assert.equal(crashed.webContents.session.listenerCount('will-download'), 1);
    farm.webContents.send = (channel, ...values) => { if (channel !== 'focus:rest-action') send(channel, ...values); };
    const interruptedAction = assert.rejects(restPopup.act({ key: 'test/one', action: 'focus' }));
    crashed.webContents.forcefullyCrashRenderer();
    await until(() => crashed.isDestroyed());
    await interruptedAction;
    farm.webContents.send = send;
    assert.equal(popup(), undefined);
    assert.equal(farm.webContents.getOSProcessId(), farmProcess);
    assert.equal(await farm.webContents.executeJavaScript("!!document.querySelector('.focus-app')"), true);
    restPopup.update(state);
    await until(() => popup() && !popup().webContents.isLoadingMainFrame());
    await until(() => popup().webContents.executeJavaScript("Array.from(document.querySelectorAll('button')).every(b=>!b.disabled)"));
    assert.equal(await popup().webContents.executeJavaScript("document.querySelectorAll('button').length"), 2);
    checks.push("actual reminder renderer crash disposes topmost window, leaves farm renderer alive and fresh update rebuilds both actions");
    const closed = popup();
    closed.close();
    assert.equal(closed.isDestroyed(), true);
    assert.equal(farm.isDestroyed(), false);
    checks.push("native Alt+F4 close dismisses threshold without quitting or pinning farm");
    restPopup.update(state);
    await until(() => popup() && !popup().webContents.isLoadingMainFrame());
    const beforeReload = popup();
    farm.reload();
    await until(() => beforeReload.isDestroyed());
    await until(() => !farm.webContents.isLoadingMainFrame());
    assert.equal(popup(), undefined);
    checks.push("farm renderer reload destroys obsolete alert, without changing timer owner");
    fs.writeFileSync(path.join(root, "artifacts/p040-native-window.json"), JSON.stringify({ checks, headless: true }, null, 2));
    console.log(JSON.stringify({ checks }, null, 2));
    app.exit(0);
  } catch (e) { console.error(e); app.exit(1); }
});
